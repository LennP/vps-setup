#!/usr/bin/env bash
source "$(dirname "${BASH_SOURCE[0]}")/../../lib/common.sh"

standalone_header "Restore recovery secret"
require_root

secret_name="dokploy_auth_secret"
restored_name="${secret_name}_restored"

status "Checking Docker Swarm"

[[ "$(docker info --format '{{.Swarm.LocalNodeState}}')" == "active" ]] \
  || fail "Docker Swarm is not active"

docker secret inspect "$restored_name" >/dev/null 2>&1 \
  && fail "Secret '$restored_name' already exists; inspect it before retrying"

status "Finding services using the original secret"

declare -a services=()

while IFS= read -r service; do
  [[ -n "$service" ]] || continue

  if docker service inspect "$service" \
    --format '{{json .Spec.TaskTemplate.ContainerSpec.Secrets}}' \
    | jq -e --arg name "$secret_name" \
      'any(.[]?; .SecretName == $name)' >/dev/null; then
    services+=("$service")
  fi
done < <(docker service ls --format '{{.Name}}')

(( ${#services[@]} > 0 )) \
  || fail "No services reference '$secret_name'"

printf '\n'
info "The following services will be updated:"

for service in "${services[@]}"; do
  info "$service"
done

printf '\n'
warn "Updating these services may temporarily restart Dokploy."

read -rp "Continue? [y/N] " confirm

[[ "$confirm" =~ ^[Yy]$ ]] || fail "Secret restoration cancelled"

printf '\n'
info "Paste the encrypted recovery secret generated by backup.sh."
printf '\n'

read -rp "Encrypted secret (Base64): " encrypted

[[ -n "$encrypted" ]] || fail "Encrypted secret is required"

printf '\n'
read -rsp "Encryption passphrase: " passphrase
printf '\n'

[[ -n "$passphrase" ]] || fail "Passphrase is required"

status "Validating encrypted recovery secret"

# Validate the entire decryption pipeline before creating the Docker secret.
# No decrypted data is stored in a file or shell variable.
if ! (
  set -o pipefail

  printf '%s' "$encrypted" \
    | base64 -d \
    | openssl enc -d -aes-256-cbc -pbkdf2 -iter 600000 \
        -pass fd:3 3<<< "$passphrase" \
    | wc -c \
    | awk '{exit ($1 == 0)}'
); then
  unset passphrase encrypted
  fail "Invalid encrypted secret or passphrase"
fi

done_msg "Recovery secret validated"

status "Creating restored Docker Swarm secret"

# Decrypt again and pipe the plaintext directly into Docker.
# The plaintext is never saved to disk or a shell variable.
if ! (
  set -o pipefail

  printf '%s' "$encrypted" \
    | base64 -d \
    | openssl enc -d -aes-256-cbc -pbkdf2 -iter 600000 \
        -pass fd:3 3<<< "$passphrase" \
    | docker secret create "$restored_name" -
); then
  unset passphrase encrypted
  docker secret rm "$restored_name" >/dev/null 2>&1 || true
  fail "Failed to create restored Docker secret"
fi

unset passphrase encrypted

done_msg "Restored Docker Swarm secret created"

for service in "${services[@]}"; do
  status "Updating $service"

  secret_target=$(docker service inspect "$service" \
    --format '{{json .Spec.TaskTemplate.ContainerSpec.Secrets}}' \
    | jq -r --arg name "$secret_name" \
      '[.[]? | select(.SecretName == $name) | .File.Name][0] // empty')

  [[ -n "$secret_target" ]] \
    || fail "Could not determine secret target for $service"

  docker service update \
    --secret-rm "$secret_name" \
    --secret-add "source=$restored_name,target=$secret_target" \
    --detach=false \
    "$service" >/dev/null

  done_msg "Updated $service"
done

done_msg "Recovery secret restored successfully"